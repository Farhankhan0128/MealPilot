function routeStep(
  sequence: number,
  label: string,
  servers: SwiggyServer[],
  tools: string[],
  purpose: string,
  optimization: string,
  confirmationGate: string,
  surface: PremiumUseCaseSurface,
): PremiumUseCaseRouteStep {
  return { sequence, label, servers, tools, purpose, optimization, confirmationGate, surface };
}

function useCase(
  id: string,
  title: string,
  tier: PremiumUseCaseTier,
  stage: PremiumUseCaseStage,
  audience: string,
  promise: string,
  baselineCalls: number,
  optimizedCalls: number,
  route: PremiumUseCaseRouteStep[],
  safetyGates: string[],
  dataBoundaries: string[],
  successMetrics: string[],
  premiumDifferentiators: string[],
): PremiumUseCaseBlueprint {
  const servers = [...new Set(route.flatMap((step) => step.servers))];
  const primaryTools = [...new Set(route.flatMap((step) => step.tools))];
  return {
    id,
    title,
    tier,
    stage,
    audience,
    promise,
    servers,
    primaryTools,
    baselineCalls,
    optimizedCalls,
    savedCalls: baselineCalls - optimizedCalls,
    route,
    safetyGates,
    dataBoundaries,
    successMetrics,
    premiumDifferentiators,
  };
}

