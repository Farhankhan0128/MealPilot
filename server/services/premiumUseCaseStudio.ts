function toolKey(server: SwiggyServer, tool: string) {
  return `${server}.${tool}`;
}

function splitToolKey(key: string): { server: SwiggyServer; tool: string } | null {
  const [server, tool] = key.split(".");
  if (!tool || !["food", "instamart", "dineout"].includes(server)) return null;
  return { server: server as SwiggyServer, tool };
}

function isSplitToolKey(value: { server: SwiggyServer; tool: string } | null): value is { server: SwiggyServer; tool: string } {
  return value !== null;
}

